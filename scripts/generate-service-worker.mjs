// The offline contingency, as a service worker written into public/.
//
// docs/ONSITE_ACTIVITY_50_MIN.md requires a paper/offline fallback and there was none: if the
// venue's wifi drops mid-activity the room stops. The app is fully client-side after first load,
// so a service worker is enough to make a session survive losing the network — which is a real
// risk at an offsite, not a hypothetical one.
//
// What is precached is chosen by weight, not by wishing. The twelve character assets are 12MB and
// only one of them is ever shown, so precaching them would spend a participant's mobile data on
// eleven pictures they will not see; they are cached at runtime as they are requested instead. The
// shell — the page, its CSS and JS, the welcome illustration, the QR — is small and is what has to
// be there before anything else can run.
//
// Generated rather than hand-written because the build hashes its own filenames: the list has to
// be read out of .next after every build or the worker precaches URLs that no longer exist.
//
// Usage: npm run build && npm run sw

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "..");
const NEXT_DIR = path.join(projectRoot, ".next");
const PUBLIC = path.join(projectRoot, "public");

if (!fs.existsSync(NEXT_DIR)) throw new Error("no .next — run `npm run build` first");

// Everything the first screen needs, plus the two files a facilitator projects.
const staticFiles = ["/guild-characters-3d.webp", "/brand/td-logo.png", "/qr.svg"]
  .filter((file) => fs.existsSync(path.join(PUBLIC, file.slice(1))));

// The build's own chunks and CSS. next/font writes its faces here too, and a session that loses
// the network without them falls back to a system font mid-question, which is exactly the kind of
// visible break this is meant to prevent.
const walk = (dir, prefix) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const full = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(full, `${prefix}/${entry.name}`) : [`${prefix}/${entry.name}`];
});
const buildAssets = walk(path.join(NEXT_DIR, "static"), "/_next/static")
  .filter((file) => /\.(js|css|woff2?)$/.test(file))
  // Source maps and the build manifest are developer files; a phone in a meeting room does not
  // need them and they are a third of the weight.
  .filter((file) => !file.endsWith(".map"));

const precache = ["/", ...staticFiles, ...buildAssets];
const version = crypto.createHash("sha1").update(precache.join("|")).digest("hex").slice(0, 12);

const worker = `// GENERATED by scripts/generate-service-worker.mjs. Do not edit: \`npm run sw\` overwrites it.
//
// Cache version ${version}. A new build produces a new version, the old cache is deleted on
// activate, and a participant mid-session keeps the worker they loaded with until they reload.
const VERSION = ${JSON.stringify(version)};
const CACHE = \`tdfb-pq-\${VERSION}\`;
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  // Individually rather than cache.addAll: addAll rejects the whole install if any one request
  // fails, and one 404 in a list this long would leave the session with no offline support at all
  // rather than with one missing file.
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => {})));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith("tdfb-pq-") && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // The page itself is network-first, so a participant who still has wifi gets the current build
  // rather than yesterday's. Everything else is cache-first: hashed assets never change under
  // their own URL, and a character PNG fetched once should not be fetched again on a venue's wifi.
  const isDocument = request.mode === "navigate";
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (!isDocument) {
      const hit = await cache.match(request);
      if (hit) return hit;
    }
    try {
      const response = await fetch(request);
      // Opaque and error responses are not worth keeping; caching a 404 would make it permanent.
      if (response.ok && response.type === "basic") await cache.put(request, response.clone());
      return response;
    } catch (error) {
      const hit = await cache.match(request) ?? (isDocument ? await cache.match("/") : undefined);
      if (hit) return hit;
      throw error;
    }
  })());
});
`;

fs.writeFileSync(path.join(PUBLIC, "sw.js"), worker);
const bytes = precache.reduce((sum, url) => {
  const file = url === "/" ? null : path.join(url.startsWith("/_next/") ? NEXT_DIR : PUBLIC,
    url.startsWith("/_next/") ? url.replace("/_next/", "") : url.slice(1));
  return sum + (file && fs.existsSync(file) ? fs.statSync(file).size : 0);
}, 0);
console.log(`public/sw.js — cache ${version}`);
console.log(`  ${precache.length} files precached, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
console.log(`  character assets are NOT precached (12 MB, one is ever shown); they cache on use`);
